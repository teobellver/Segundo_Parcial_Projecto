void SetPin ( uint8_t puerto , uint8_t bit , uint8_t actividad );
void ClrPin ( uint8_t puerto , uint8_t bit , uint8_t actividad );
void ToggleOutput ( uint8_t puerto , uint8_t bit );
uint8_t GetPin ( uint8_t puerto , uint8_t bit , uint8_t actividad );

